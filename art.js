/* ---------- render: kontur → wypełnienia → detale ---------- */
function paint(parts,ink,ghost){
  const OL='stroke-linejoin="round" stroke-linecap="round"';
  let A='',B='',C='';
  for(const p of parts){
    if(!p||p.m>=2) continue;
    A+= p.k ? `<path d="${p.d}" fill="none" stroke="${ink}" stroke-width="${p.k+7}" ${OL}/>`
            : `<path d="${p.d}" fill="${ink}" stroke="${ink}" stroke-width="7" ${OL}/>`;
  }
  if(ghost) return A;
  for(const p of parts){
    if(!p||p.m>=2) continue;
    B+= p.k ? `<path d="${p.d}" fill="none" stroke="${p.f}" stroke-width="${p.k}" ${OL}/>`
            : `<path d="${p.d}" fill="${p.f}"/>`;
  }
  for(const p of parts) if(p&&p.m===1) C+=`<path d="${p.d}" fill="none" stroke="${ink}" stroke-width="2.5" ${OL}/>`;
  for(const p of parts){
    if(!p) continue;
    if(p.m===2) C+=`<path d="${p.d}" fill="${p.f||'none'}" stroke="${ink}" stroke-width="${p.sw||2.4}" ${OL}/>`;
    if(p.m===3) C+=`<path d="${p.d}" fill="${p.f}" opacity="${p.op!==undefined?p.op:.5}"/>`;
  }
  return A+B+C;
}

function drawSpecies(sp,mode,palOverride){
  const pal=palOverride||PAL[(sp.o&&sp.o.p)||0]||PAL[0];
  const out=(ARCH[sp.a]||A_thero)(pal,sp.o||{});
  const ghost=mode==='ghost';
  const ink=ghost?'#BCAF93':pal[2];
  const inner=`<g transform="translate(100,76) scale(${out.sc||1}) translate(-100,-76)">${paint(out.p,ink,ghost)}</g>`;
  const shadow=ghost?''
    : out.fly?''
    : out.water
      ? '<g fill="none" stroke="#8FC3D6" stroke-width="3" stroke-linecap="round" opacity=".5"><path d="M14,124 C36,118 56,128 78,122"/><path d="M104,134 C126,128 146,138 168,132"/></g>'
      : '<ellipse cx="100" cy="133" rx="56" ry="5" fill="rgba(60,40,20,.15)"/>';
  return `<svg viewBox="0 0 200 140" xmlns="http://www.w3.org/2000/svg" class="dsvg">${shadow}${inner}</svg>`;
}
